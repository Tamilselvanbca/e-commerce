const orderSmsText = {
  confirmed: () => `is confirmed. We're getting it ready.`,
  processing: () => `is being packed.`,
  shipped: (o) => {
    const s = o.shipment;
    return `has shipped${s?.awb ? ` via ${s.courier ?? 'courier'} (AWB ${s.awb})` : ''}.${s?.trackingUrl ? ` Track: ${s.trackingUrl}` : ''}`;
  },
  delivered: () => `has been delivered. We hope you love it!`,
  cancelled: (o) => `has been cancelled.${o.paymentStatus === 'paid' || o.paymentStatus === 'refunded' ? ' Your payment will be refunded in 5-7 business days.' : ''}`,
};

/** Fire-and-forget SMS to the customer about an order status change. Never throws. */
export function queueOrderStatusSms(order, status) {
  if (!config.sms.orderUpdates || !order.phone || !orderSmsText[status]) return;
  const link = `${config.frontendUrl}/account/orders/${encodeURIComponent(order.orderNumber)}`;
  const text = `${config.store.name}: Your order ${order.orderNumber} ${orderSmsText[status](order)} ${link}`;
  setImmediate(async () => {
    try {
      await twilioMessage(order.phone, text);
      logger.info({ orderNumber: order.orderNumber, status }, '[sms] order update sent');
    } catch (err) {
      logger.error({ err, orderNumber: order.orderNumber, status }, '[sms] order update failed');
    }
  });
}
