// SMS delivery. For the console, msg91 and twilio OTP providers the code is generated
// and verified by this app (services/otp.js) and providers only deliver the message.
// With twilio_verify, Twilio Verify generates, sends and checks the code itself.
// Order status updates are sent as plain SMS through Twilio Programmable Messaging.
import { config } from '../config.js';
import { AppError } from '../lib/errors.js';
import { logger } from '../lib/logger.js';

async function sendViaConsole(phone, code) {
  logger.info({ phone }, `[OTP] Login code for ${phone}: ${code}`);
}

/** MSG91 OTP API v5. The DLT-approved template must contain the ##OTP## variable. */
async function sendViaMsg91(phone, code) {
  const { authKey, templateId } = config.otp.msg91;
  if (!authKey || !templateId) throw new Error('MSG91_AUTH_KEY and MSG91_TEMPLATE_ID are required');
  const url = new URL('https://control.msg91.com/api/v5/otp');
  url.searchParams.set('template_id', templateId);
  url.searchParams.set('mobile', phone.replace(/^\+/, ''));
  url.searchParams.set('otp', code);
  url.searchParams.set('otp_expiry', String(Math.ceil(config.otp.ttlSeconds / 60)));
  const res = await fetch(url, {
    method: 'POST',
    headers: { authkey: authKey, 'content-type': 'application/json' },
    body: '{}',
    signal: AbortSignal.timeout(10_000),
  });
  const body = await res.json().catch(() => ({}));
  if (!res.ok || body.type === 'error') {
    throw new Error(`MSG91 error: ${body.message ?? res.status}`);
  }
}

function twilioCredentials() {
  const { accountSid, authToken } = config.otp.twilio;
  if (!accountSid || !authToken) throw new Error('TWILIO_ACCOUNT_SID and TWILIO_AUTH_TOKEN are required');
  return { accountSid, authToken };
}

/** POSTs a form to a Twilio API. Throws an Error carrying Twilio's `status` and `code` on failure. */
async function twilioPost(url, params) {
  const { accountSid, authToken } = twilioCredentials();
  const res = await fetch(url, {
    method: 'POST',
    headers: {
      authorization: `Basic ${Buffer.from(`${accountSid}:${authToken}`).toString('base64')}`,
      'content-type': 'application/x-www-form-urlencoded',
    },
    body: new URLSearchParams(params),
    signal: AbortSignal.timeout(10_000),
  });
  const body = await res.json().catch(() => ({}));
  if (!res.ok) {
    const err = new Error(`Twilio error ${res.status}: ${body.message ?? 'unknown'}`);
    err.status = res.status;
    err.code = body.code;
    throw err;
  }
  return body;
}

/** Sends a plain SMS through Twilio Programmable Messaging. */
async function twilioMessage(to, text) {
  const { accountSid } = twilioCredentials();
  const { from, messagingServiceSid } = config.otp.twilio;
  if (!(from || messagingServiceSid)) throw new Error('TWILIO_FROM or TWILIO_MESSAGING_SERVICE_SID is required');
  const params = { To: to, Body: text };
  if (messagingServiceSid) params.MessagingServiceSid = messagingServiceSid;
  else params.From = from;
  await twilioPost(`https://api.twilio.com/2010-04-01/Accounts/${accountSid}/Messages.json`, params);
}

/** Twilio Programmable Messaging (code generated by this app). */
async function sendViaTwilio(phone, code) {
  await twilioMessage(
    phone,
    `${code} is your ${config.store.name} login code. It expires in ${Math.ceil(config.otp.ttlSeconds / 60)} minutes. Do not share it with anyone.`,
  );
}

const verifyUrl = (path) => `https://verify.twilio.com/v2/Services/${config.otp.twilio.verifyServiceSid}/${path}`;

/**
 * Twilio Verify: Twilio generates and sends the code; `code` is unused. The company
 * name in the SMS is the Verify service's friendly name; the wording comes from
 * TWILIO_VERIFY_TEMPLATE_SID (one of Twilio's pre-approved templates).
 */
async function sendViaTwilioVerify(phone) {
  const params = { To: phone, Channel: 'sms' };
  if (config.otp.twilio.verifyTemplateSid) params.TemplateSid = config.otp.twilio.verifyTemplateSid;
  await twilioPost(verifyUrl('Verifications'), params);
}

/**
 * Checks a code with Twilio Verify. Returns true when approved, false when wrong.
 * Throws AppError OTP_EXPIRED when Twilio has no pending verification (expired,
 * already used or too many attempts) and SMS_FAILED when Twilio can't be reached.
 */
export async function checkTwilioVerification(phone, code) {
  try {
    const result = await twilioPost(verifyUrl('VerificationCheck'), { To: phone, Code: code });
    return result.status === 'approved';
  } catch (err) {
    if (err.status === 404 || err.code === 60202) {
      throw new AppError(400, 'OTP_EXPIRED', 'This code has expired. Please request a new one.');
    }
    logger.error({ err }, 'Twilio Verify check failed');
    throw new AppError(502, 'SMS_FAILED', 'We could not check the code right now. Please try again shortly.');
  }
}

const providers = { console: sendViaConsole, msg91: sendViaMsg91, twilio: sendViaTwilio, twilio_verify: sendViaTwilioVerify };

export async function sendOtpSms(phone, code) {
  try {
    await providers[config.otp.provider](phone, code);
  } catch (err) {
    logger.error({ err, provider: config.otp.provider }, 'Failed to send OTP SMS');
    if (err.code === 60203) {
      throw new AppError(429, 'RATE_LIMITED', 'Too many codes requested for this number. Try again later.', { retryAfter: 600 });
    }
    throw new AppError(502, 'SMS_FAILED', 'We could not send the code right now. Please try again shortly.');
  }
}

